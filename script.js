// FUNÇÃO PARA ALTERAR O IDIOMA

function changeLanguage(language) {

    const selectedLanguage = translations[language];

    if (!selectedLanguage) {
        return;
    }

    // Atualiza o idioma do documento
    document.documentElement.lang =
        language === "pt" ? "pt-BR" : language;

    // Atualiza o título da página
    document.title = selectedLanguage.pageTitle;

    // Atualiza todos os textos traduzidos
    document.querySelectorAll("[data-i18n]").forEach(element => {

        const key = element.getAttribute("data-i18n");

        if (selectedLanguage[key]) {
            element.innerHTML = selectedLanguage[key];
        }

    });

    // Salva o idioma escolhido
    localStorage.setItem("careerLabLanguage", language);

}


// SELETOR DE IDIOMAS

const languageSelect = document.getElementById("languageSelect");

languageSelect.addEventListener("change", function () {

    changeLanguage(this.value);

});


// CARREGA O IDIOMA SALVO

const savedLanguage =
    localStorage.getItem("careerLabLanguage") || "pt";

languageSelect.value = savedLanguage;

changeLanguage(savedLanguage);


